// Expands CATEGORY_SPEC into every Wikidata subclass and writes
// netlify/lib/category-data.mjs, so the game never has to walk class trees
// while players wait.
//
//   npm run build-categories

import { writeFileSync } from 'node:fs';
import { CATEGORY_SPEC } from '../netlify/lib/category-spec.mjs';

const USER_AGENT = 'LetterBlitz/1.0 (https://github.com/Jeremytpk/Letter-Blitz)';
const OUT = new URL('../netlify/lib/category-data.mjs', import.meta.url);

async function sparql(query) {
  const res = await fetch(`https://query.wikidata.org/sparql?query=${encodeURIComponent(query)}`, {
    headers: { 'User-Agent': USER_AGENT, Accept: 'application/sparql-results+json' },
  });
  if (!res.ok) throw new Error(`SPARQL ${res.status}: ${(await res.text()).slice(0, 200)}`);
  const data = await res.json();
  return data.results.bindings.map((b) => Number(b.x.value.split('/Q').pop()));
}

const subclassesOf = (roots) =>
  sparql(`SELECT DISTINCT ?x WHERE { VALUES ?r { ${roots.map((q) => `wd:${q}`).join(' ')} } ?x wdt:P279* ?r . }`);

const data = { classes: {}, occupations: {}, capitals: [] };
for (const [catId, spec] of Object.entries(CATEGORY_SPEC)) {
  if (spec.classes) data.classes[catId] = (await subclassesOf(spec.classes)).sort((a, b) => a - b);
  if (spec.occupations) data.occupations[catId] = (await subclassesOf(spec.occupations)).sort((a, b) => a - b);
  console.log(catId.padEnd(10), 'classes', (data.classes[catId] || []).length, 'occupations', (data.occupations[catId] || []).length);
}
// Current capitals of countries (statements without an end date).
data.capitals = (
  await sparql(`SELECT DISTINCT ?x WHERE {
    VALUES ?r { wd:Q6256 wd:Q3624078 } ?c wdt:P31/wdt:P279* ?r .
    ?c p:P36 ?st . ?st ps:P36 ?x . FILTER NOT EXISTS { ?st pq:P582 ?end }
  }`)
).sort((a, b) => a - b);
console.log('capitals  ', data.capitals.length);

writeFileSync(OUT, `// Generated by scripts/build-categories.mjs — do not edit by hand.\nexport default ${JSON.stringify(data)};\n`);
console.log('wrote', OUT.pathname);
